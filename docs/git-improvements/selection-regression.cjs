const {expect}=require('chai')
const sinon=require('sinon')
const React=require('react')
const {render,screen,fireEvent,act,cleanup}=require('@testing-library/react')
const requests=require('../../services/web/frontend/js/infrastructure/fetch-json')
const {GitSyncView}=require('../../services/web/frontend/js/features/git-sync/git-sync-panel')
describe('Audit: remote checks and manual file selection',function(){
 afterEach(()=>{cleanup();sinon.restore()})
 it('preserves selection after a successful periodic remote check',async function(){
  let tick,completeFetch
  sinon.stub(window,'setInterval').callsFake((fn,ms)=>{if(ms===60000)tick=fn;return 1})
  sinon.stub(window,'clearInterval')
  sinon.stub(requests,'getJSON').callsFake(async url=>url.endsWith('/graph')?{commits:[],branches:[],truncated:false}:url.endsWith('/changes')?{files:[{path:'main.tex',action:'modify'}],fingerprint:'one',mergeRequired:false}:{connected:true,pushEnabled:true,remoteUrl:'https://github.com/owner/paper',branch:'main',state:'review-applied'})
  sinon.stub(requests,'postJSON').callsFake(()=>new Promise(resolve=>{completeFetch=resolve}))
  render(React.createElement(GitSyncView,{projectId:'audit'}))
  await screen.findByText('main',{selector:'strong'})
  fireEvent.click(screen.getByRole('tab',{name:'Changes'}))
  fireEvent.click(await screen.findByRole('checkbox',{name:'Include main.tex in commit'}))
  expect(screen.getByRole('checkbox',{name:'Include main.tex in commit'}).checked).to.equal(true)
  expect(tick).to.be.a('function')
  await act(async()=>{tick();await Promise.resolve()})
  expect(completeFetch).to.be.a('function')
  await act(async()=>{completeFetch({});await Promise.resolve()})
  expect((await screen.findByRole('checkbox',{name:'Include main.tex in commit'})).checked).to.equal(true)
 })
})

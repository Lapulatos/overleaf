// @ts-check
/**
 * Shared type definitions for overleaf-agent.
 */

/**
 * @typedef {Object} AgentConfig
 * @property {number} port
 * @property {string} [host] Listen IP; defaults to 127.0.0.1.
 * @property {string} backend
 * @property {Function} [prepareEnvironmentRepair] Prepare-only maintenance callback.
 * @property {string} [maintenanceConfig] Operator-owned environment maintenance configuration path.
 * @property {string} [compilerImage] Pinned Docker compiler image enables the document harness.
 * @property {string} [apiKey]
 * @property {string} [endpoint]
 * @property {string} [provider]
 * @property {string} [model]
 * @property {string} [speechPython] Optional local transcription interpreter path.
 * @property {string} [speechModel] Optional installed local Whisper model directory.
 * @property {number} maxSteps
 * @property {number} timeout
 * @property {AbortSignal} [signal]
 * @property {string} [agentToken]
 * @property {string} [sandbox]
 * @property {number} [maxBudgetUsd]
 * @property {string} [waHostUrl]
 *   WA Host Server base URL for agent API proxy calls.
 * @property {string} [agentApiSecret]
 *   Shared secret for agent API token validation (matches OVERLEAF_AGENT_API_SECRET).
 * @property {number} [maxConcurrentTasks]
 *   Cap on simultaneously running tasks. POST /agent/task returns 429 when reached.
 * @property {string} [logLevel]
 *   Logger level: debug | info | warn | error. Default: info.
 */

/**
 * @typedef {Object} AgentTaskRequest
 * @property {string} taskId
 * @property {string} type
 * @property {Object} context
 * @property {string} context.projectId
 * @property {string} context.userId
 * @property {string} context.documentContent
 * @property {string} [context.bibContent]
 * @property {string} [context.compileLog]
 * @property {{ turns: Array, omittedTurns: number }} [context.conversation]
 * @property {{ from: number; to: number }} [context.selection]
 * @property {string} [context.apiToken]
 *   Project-scoped HMAC token for agent API bridge calls.
 *   Generated by WA controller when task is created. Expires after 30 min.
 * @property {string} [context.waHostUrl]
 *   Base URL of the WA Host Server for API proxy calls.
 *   Default: http://127.0.0.1:3050
 * @property {{ docs: Array, files: Array }} [context.projectEntities]
 *   Pre-fetched project entities listing (docs + files with paths).
 *   When present, the agent knows the project structure upfront.
 * @property {Object} [context.fileMap]
 *   Map of file paths to { docId, version } for diff→docId resolution.
 *   Example: { "main.tex": { docId: "abc123", version: 5 } }
 * @property {string} instruction
 * @property {number} [maxSteps]
 * @property {number} [timeout]
 * @property {string} [model]
 * @property {string} [effort]
 */

/**
 * @typedef {'pending'|'running'|'completed'|'failed'|'timeout'|'cancelled'} TaskStatus
 */


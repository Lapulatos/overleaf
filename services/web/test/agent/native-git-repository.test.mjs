test('native apply stages and unstages selected hunks without including other edits and rejects stale diffs', async t => {
  const { repository: repo } = await fixture(t)
  const base = Array.from({ length: 40 }, (_, i) => `Original line ${i}`).join('\n') + '\n'
  await writeFile(Path.join(repo.directory, 'paper.tex'), base)
  await repo.stage(['paper.tex']); await repo.commit('Add long paper')
  const changed = base.replace('Original line 1\n', 'First changed line\nExtra line\n').replace('Original line 35', 'Second changed line')
  await writeFile(Path.join(repo.directory, 'paper.tex'), changed)
  const view = await repo.fileHunks('paper.tex')
  assert.equal(view.hunks.length, 2)
  await repo.applyHunks('paper.tex', [1], view.fingerprint)
  const indexed = await native(repo.directory, 'show', ':paper.tex')
  assert.match(indexed, /Second changed line/)
  assert.doesNotMatch(indexed, /First changed line|Extra line/)
  assert.equal(await readFile(Path.join(repo.directory, 'paper.tex'), 'utf8'), changed)
  const staged = await repo.fileHunks('paper.tex', true)
  await repo.applyHunks('paper.tex', [0], staged.fingerprint, true)
  assert.equal(await repo.diff({ staged: true }), '')
  await repo.applyHunks('paper.tex', [0], view.fingerprint)
  await repo.commit('Commit first hunk only')
  assert.match(await repo.show('HEAD', 'paper.tex'), /First changed line/)
  assert.doesNotMatch(await repo.show('HEAD', 'paper.tex'), /Second changed line/)
  const stale = await repo.fileHunks('paper.tex')
  await writeFile(Path.join(repo.directory, 'paper.tex'), changed + 'New edit\n')
  await assert.rejects(repo.applyHunks('paper.tex', [0], stale.fingerprint), error => error.status === 409)
  assert.equal(await repo.diff({ staged: true }), '')
})


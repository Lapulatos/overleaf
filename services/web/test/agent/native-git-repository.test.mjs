const exec = promisify(execFile)
async function native(directory, ...args) {
  return (await exec('git', ['-C', directory, ...args], { env: { ...process.env, GIT_CONFIG_NOSYSTEM: '1', GIT_TERMINAL_PROMPT: '0' } })).stdout.trim()
}
async function fixture(t) {
  const root = await mkdtemp(Path.join(tmpdir(), 'overleaf-native-git-'))
  t.after(() => rm(root, { recursive: true, force: true }))
  const repository = await GitRepository.init(Path.join(root, 'repo'), { worktreeRoot: Path.join(root, 'worktrees'), allowLocalRemotes: true }, 'repo-test')
  await repository.author('Fixture Author', 'fixture@example.test')
  await writeFile(Path.join(repository.directory, 'frontmatter.tex'), 'Original title\n')
  await writeFile(Path.join(repository.directory, 'methods.tex'), 'Original methods\n')
  await repository.stage(['frontmatter.tex', 'methods.tex'])
  const initial = await repository.commit('Initial manuscript')
  return { root, repository, initial }
}

test('B commit, old branch checkout, and branch-specific unfinished files follow native worktrees', async t => {
  const { repository: repo, initial } = await fixture(t)
  await repo.createBranch('A')
  await repo.createBranch('B')
  await repo.createBranch('C')
  const b = await repo.branchWorktree('B')
  assert.equal((await b.status()).branch, 'B')
  await writeFile(Path.join(b.directory, 'frontmatter.tex'), 'Title committed on B\n')
  await writeFile(Path.join(b.directory, 'methods.tex'), 'Unfinished B methods\n')
  await b.stage(['frontmatter.tex'])
  const bCommit = await b.commit('Update B title')
  assert.notEqual(bCommit, initial)
  assert.equal(await native(b.directory, 'rev-parse', 'refs/heads/B'), bCommit)
  assert.deepEqual((await b.status()).files.map(file => file.path), ['methods.tex'])
  const a = await b.branchWorktree('A')
  assert.equal(await a.head(), initial)
  assert.equal(await readFile(Path.join(a.directory, 'frontmatter.tex'), 'utf8'), 'Original title\n')
  assert.deepEqual((await a.status()).files, [])
  await writeFile(Path.join(a.directory, 'frontmatter.tex'), 'Unfinished A title\n')
  const againB = await a.branchWorktree('B')
  assert.equal(await readFile(Path.join(againB.directory, 'frontmatter.tex'), 'utf8'), 'Title committed on B\n')
  assert.equal(await readFile(Path.join(againB.directory, 'methods.tex'), 'utf8'), 'Unfinished B methods\n')
  const againA = await againB.branchWorktree('A')
  assert.equal(await readFile(Path.join(againA.directory, 'frontmatter.tex'), 'utf8'), 'Unfinished A title\n')
  const old = await againA.branchWorktree('repo-test')
  assert.deepEqual((await old.status()).files, [])
  assert.equal(await old.head(), initial)
  const branches = await repo.branches()
  assert.equal(branches.length, 4)
  assert.equal(branches.find(branch => branch.name === 'B').commit, bCommit)
  assert.equal(branches.find(branch => branch.name === 'A').commit, initial)
  assert.equal(branches.find(branch => branch.name === 'B').subject, 'Update B title')
  assert.equal(branches.find(branch => branch.name === 'B').author, 'Fixture Author')
  assert.ok(Number.isFinite(Date.parse(branches[0].date)))
  const graph = await repo.graph()
  assert.equal(graph[0].hash, bCommit)
  assert.deepEqual(graph[0].parents, [initial])
})

